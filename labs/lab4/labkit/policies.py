REFUND = """# 退款政策（SOP-REFUND v2.2）

## 1. 适用范围
本政策适用于所有通过线上渠道支付的订单，包括商品质量问题、少发漏发、重复扣款、订单取消后未自动退款等情形。不适用于礼品卡、积分兑换和线下门店订单。

## 2. 核实要求
处理任何退款前，必须先查询订单详情和该订单的全部支付记录，确认：
- 退款对应的支付记录状态为 captured；
- 退款金额不超过该支付记录的可退金额；
- 如果是重复扣款，只退多出来的那一笔，保留一笔正常扣款。

## 3. 金额权限（核心规则）
| 单笔退款金额 | 处理方式 |
|---|---|
| ≤ 200 元 | 客服可直接退款 |
| 200 元 < 金额 ≤ 1000 元 | 必须先调用 request_approval 申请审批，批准后再退款 |
| > 1000 元 | 不得自行退款，转人工坐席（escalate_to_human） |

注意：VIP 客户另有升级规则，见《升级政策》。两份政策同时适用时，以要求更严格的一方为准。

## 4. 退款原因
退款时 reason 字段写明具体原因（例如“重复扣款，退还多扣的一笔”“商品破损”），不要只写“退款”。

## 5. 通知客户
退款完成后通知客户退款金额和预计到账时间（原路退回，1–3 个工作日）。

## 6. 历史背景
2024 年以前，退款审批通过邮件完成，平均耗时 2 天。2025 年起改为系统审批，200–1000 元区间的退款大多在几分钟内获批。审批被拒的常见原因是金额与支付记录不符，或者同一笔支付已经退过款。

## 7. 常见问题
- 问：客户要求退款到其他银行卡怎么办？答：一律原路退回，不支持更换退款账户。
- 问：部分退款怎么处理？答：按实际金额退款，金额权限按单笔退款金额判断。
- 问：客户同时提出退款和补偿怎么办？答：分别按退款政策和补偿政策处理。
""" + _COMMON_TAIL

ESCALATION = """# 升级政策（SOP-ESCALATION v1.4）

## 1. 目的
部分工单涉及合规风险或重要客户，需要由人工坐席处理。本政策规定哪些情况必须升级，以及升级后一线客服还能做什么。

## 2. 必须升级的情形（核心规则）
出现以下任一情形，必须调用 escalate_to_human 转人工，并且**不得**自行退款、发券或承诺任何赔偿：
1. 工单中出现法律或监管相关字眼：律师、起诉、法院、消协、市场监管、12315、媒体曝光；
2. VIP 客户（客户资料 tier = vip）提出的单笔金额超过 500 元的退款或赔偿；
3. 单笔退款金额超过 1000 元（见《退款政策》）。

## 3. 升级后的处理
升级后，一线客服只需礼貌告知客户“已转交专人处理，将在 24 小时内联系您”，然后提交工单。不要在回复中讨论责任归属。

## 4. 不需要升级的情形
- 普通客户的小额问题，即使语气激烈，只要没有出现第 2 节的字眼，也按常规流程处理；
- VIP 客户 500 元以内的问题按常规流程处理。

## 5. 历史背景
2025 年第二季度，曾有一线客服在客户提到“消协”后自行承诺高额赔偿，导致后续处理被动。此后本政策将法律字眼列为强制升级条件。

## 6. 常见问题
- 问：客户只是说“要投诉你们”算不算？答：只说投诉不算，提到消协、12315、律师等才算。
- 问：VIP 客户的身份在哪里看？答：客户资料中的 tier 字段。
""" + _COMMON_TAIL

COMPENSATION = """# 补偿政策（SOP-COMPENSATION v3.0）

## 1. 适用范围
本政策适用于因物流延误、服务失误造成的客户补偿，补偿形式为优惠券（issue_coupon）。

## 2. 物流延误补偿（核心规则）
延误天数 = 实际送达日期 − 承诺送达日期（按自然日计算）。

| 延误天数 | 优惠券面额 |
|---|---|
| 1–3 天 | 10 元 |
| 4–7 天 | 30 元 |
| 8 天及以上 | 50 元，并在回复中致歉 |

例外：如果延误是因为客户在发货后修改了收货地址（物流记录 notes 中会注明），不发放补偿，向客户说明原因。

## 3. 其他补偿
- 商品破损、少发漏发：按《退款政策》退款，不额外发券；
- 客服服务失误：由人工坐席评估。

## 4. 发放规则
- 同一订单只补偿一次；
- 发券后通知客户券的面额和有效期（30 天）。

## 5. 历史背景
3.0 版之前，延误补偿按订单金额的百分比计算，客户难以理解。3.0 版改为固定面额，便于一线客服执行。

## 6. 常见问题
- 问：客户要求现金补偿怎么办？答：一线客服只能发券，现金补偿需转人工。
- 问：延误半天算不算？答：按自然日计算，同一天送达不算延误。
""" + _COMMON_TAIL

